/* ---- Toasts ---- */
const TOAST_ICON = { success: 'checkCircle', error: 'alertCircle', warning: 'alertTriangle', info: 'info' };
function showToast({ type = 'info', title, message, duration = 4200 }){
  const region = qs('#toastRegion');
  if (!region) return;
  const el = document.createElement('div');
  el.className = `toast ${type}`;
  el.setAttribute('role', 'status');
  el.innerHTML = `
    <span class="toast__icon">${icon(TOAST_ICON[type])}</span>
    <div>
      <div class="toast__title">${escapeHTML(title)}</div>
      ${message ? `<div class="toast__msg">${escapeHTML(message)}</div>` : ''}
    </div>
    <button class="toast__close" aria-label="${t('close')}">${icon('x')}</button>
  `;
  region.appendChild(el);
  const remove = () => {
    el.classList.add('leaving');
    setTimeout(() => el.remove(), 200);
  };
  el.querySelector('.toast__close').addEventListener('click', remove);
  if (duration) setTimeout(remove, duration);
}

/* ---- Modal ---- */
function openModal({ title, bodyHTML, footerHTML, onMount, size }){
  closeModal();
  const backdrop = document.createElement('div');
  backdrop.className = 'modal-backdrop';
  backdrop.id = 'activeModal';
  backdrop.innerHTML = `
    <div class="modal" role="dialog" aria-modal="true" aria-labelledby="modalTitle" ${size ? `style="max-width:${size}"` : ''}>
      <div class="modal__header">
        <h3 id="modalTitle">${escapeHTML(title)}</h3>
        <button class="modal__close" aria-label="${t('close')}">${icon('x')}</button>
      </div>
      <div class="modal__body">${bodyHTML}</div>
      ${footerHTML ? `<div class="modal__footer">${footerHTML}</div>` : ''}
    </div>
  `;
  document.body.appendChild(backdrop);
  document.body.style.overflow = 'hidden';
  backdrop.addEventListener('click', (e) => { if (e.target === backdrop) closeModal(); });
  backdrop.querySelector('.modal__close').addEventListener('click', closeModal);
  document.addEventListener('keydown', escCloseModal);
  if (onMount) onMount(backdrop);
  const focusable = backdrop.querySelector('input, button, select, textarea');
  if (focusable) focusable.focus();
  return backdrop;
}
function escCloseModal(e){ if (e.key === 'Escape') closeModal(); }
function closeModal(){
  const el = qs('#activeModal');
  if (el){ el.remove(); document.body.style.overflow = ''; }
  document.removeEventListener('keydown', escCloseModal);
}

function openConfirm({ title, message, confirmLabel, danger = true, onConfirm }){
  const backdrop = openModal({
    title,
    bodyHTML: `<p class="mb-0">${escapeHTML(message)}</p>`,
    footerHTML: `
      <button class="btn btn-secondary" data-act="cancel">${t('cancel')}</button>
      <button class="btn ${danger ? 'btn-danger' : 'btn-primary'}" data-act="confirm">${escapeHTML(confirmLabel || t('confirm'))}</button>
    `,
  });
  backdrop.querySelector('[data-act="cancel"]').addEventListener('click', closeModal);
  backdrop.querySelector('[data-act="confirm"]').addEventListener('click', () => {
    closeModal();
    onConfirm && onConfirm();
  });
}

